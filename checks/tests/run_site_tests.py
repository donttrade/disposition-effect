#!/usr/bin/env python3
"""Run the three v1 site test files against a local directory (docs/ or site/_site).

    python3 checks/tests/run_site_tests.py docs            # today's live pages, served locally
    python3 checks/tests/run_site_tests.py site/_site      # the v2 build
    python3 checks/tests/run_site_tests.py docs --record checks/tests/baseline-docs.txt

Why a runner: the files were written for https://donttrade.ca and read DT_BASE. This
serves the directory on 127.0.0.1 (random port), sets DT_BASE, turns off external link
checks and request spacing, and prints one PASS/FAIL/SKIP/XFAIL line per test, so the
result can be compared with a recorded baseline line by line.

Tests that only make sense on the live host (HTTPS redirects, HSTS, GitHub API scans)
still run; their result against a local server is recorded as-is in the baseline.
"""
import functools
import http.server
import os
import re
import subprocess
import sys
import threading

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
FILES = ["test_site_functional.py", "test_site_content.py", "test_site_security.py"]


class Quiet(http.server.SimpleHTTPRequestHandler):
    extensions_map = {**http.server.SimpleHTTPRequestHandler.extensions_map, ".js": "text/javascript"}

    def log_message(self, *a):
        pass


def main(argv):
    if not argv:
        print(__doc__)
        return 2
    root = os.path.abspath(os.path.join(REPO, argv[0]))
    record = argv[argv.index("--record") + 1] if "--record" in argv else None
    if not os.path.isdir(root):
        print(f"not a directory: {root}", file=sys.stderr)
        return 2
    srv = http.server.ThreadingHTTPServer(("127.0.0.1", 0), functools.partial(Quiet, directory=root))
    threading.Thread(target=srv.serve_forever, daemon=True).start()
    base = f"http://127.0.0.1:{srv.server_address[1]}"
    env = {**os.environ, "DT_BASE": base, "DT_SKIP_EXTERNAL": "1", "DT_DELAY": "0"}
    junit = os.path.join(os.environ.get("TMPDIR", "/tmp"), f"dt-site-tests-{os.getpid()}.xml")
    cmd = [sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", "--tb=line", "--junitxml", junit] + \
          [os.path.join(HERE, f) for f in FILES]
    r = subprocess.run(cmd, cwd=REPO, env=env, capture_output=True, text=True)
    srv.shutdown()
    lines, reasons = [], []
    import xml.etree.ElementTree as ET
    for tc in ET.parse(junit).getroot().iter("testcase"):
        # the random port is in parametrised names; replace it so runs compare line by line
        name = tc.get("classname", "").split(".")[-1] + ".py::" + tc.get("name").replace(base, "BASE")
        status = "PASSED"
        for kid in tc:
            if kid.tag in ("failure", "error"):
                status = "FAILED"
                reasons.append(f"  {name}: {(kid.get('message') or '').splitlines()[0][:220] if kid.get('message') else ''}")
            elif kid.tag == "skipped":
                status = "XFAIL" if (kid.get("type") == "pytest.xfail") else "SKIPPED"
                if status == "SKIPPED":
                    name += f"  ({(kid.get('message') or '')[:100]})"
        lines.append(f"{status:8} {name}")
    os.remove(junit)
    out = "\n".join(sorted(lines, key=lambda s: s[9:])) + "\n"
    print(out, end="")
    print("\n".join(reasons))
    print(r.stdout.strip().splitlines()[-1] if r.stdout.strip() else r.stderr[-2000:])
    if record:
        with open(os.path.join(REPO, record), "w", encoding="utf-8") as f:
            f.write(f"# v1 site tests against {argv[0]}/ served locally (DT_SKIP_EXTERNAL=1).\n"
                    f"# Generated by checks/tests/run_site_tests.py. One line per test; failure reasons at the end.\n"
                    + out + "# failure reasons\n" + "\n".join("#" + x for x in reasons) + "\n")
    return r.returncode


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
