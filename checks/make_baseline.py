#!/usr/bin/env python3
"""One-off: writes checks/urls-baseline.txt from today's docs/ (main @ e5e6234).

Lines are URL paths ("/pricing/" for docs/pricing/index.html, "/feed.xml" for a
file) and "path#id" for ids that links point at: every internal href with a
fragment across docs/, plus the /pricing/ section ids the plan lists. build.py
fails if any of them disappears. Re-run only on purpose: the baseline is the
promise that no URL moves.
"""
import os
import re

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS = os.path.join(REPO, "docs")
PRICING_IDS = ["firms", "copy-leader", "claims-test", "platforms", "traders", "researchers", "payment", "refunds",
               "history", "questions"]

paths = set()
ids = set()
for root, dirs, files in os.walk(DOCS):
    for name in files:
        rel = "/" + os.path.relpath(os.path.join(root, name), DOCS).replace(os.sep, "/")
        if rel.endswith("/index.html"):
            rel = rel[: -len("index.html")]
        paths.add(rel)
        if name.endswith(".html"):
            with open(os.path.join(root, name), encoding="utf-8") as f:
                for href in re.findall(r'href="(/[^"#]*)#([^"]+)"', f.read()):
                    ids.add(href)
for i in PRICING_IDS:
    ids.add(("/pricing/", i))
with open(os.path.join(REPO, "checks", "urls-baseline.txt"), "w", encoding="utf-8") as f:
    f.write("# Every URL of today's docs/ (main @ e5e6234) and every linked id. Generated by make_baseline.py.\n")
    for p in sorted(paths):
        f.write(p + "\n")
    for p, i in sorted(ids):
        f.write(f"{p}#{i}\n")
print(len(paths), "paths,", len(ids), "ids")
